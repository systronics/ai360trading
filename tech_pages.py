"""
tech_pages.py v1.0 (2026-11-15 NEW) - one evergreen WEBSITE page per AI360 Technology Short, for search (SEO) and for a real link from each video back to the site.
Each page = the topic's own steps in text (the Short's narration, without the shared 'see you tomorrow' line), the embedded YouTube video, the real search phrases of that topic as
'people also search', an AI/not-a-repair-guide disclosure, the owner's service line (_data/tech_cta.txt) and a link to the hub /tech-tips/. Pages are created ONLY for topics in
_data/tech_done.json (i.e. a real Short exists), one file per topic `_pages/tt-<key>.html` (permalink /tech-tips/<slug>/), plus `_data/tech_pages.json` that feeds the hub page
`_pages/tech-tips.html` (a Liquid loop, no per-topic edit). Idempotent: running twice writes the same bytes. No network, no secrets, fail-open (a bad topic is skipped, never raises).
Every page text is unique (the topic's own lines + tags); nothing is generated by an AI call. VideoObject JSON-LD uses the real video id and publish time.
USAGE: python tech_pages.py            (writes into _pages and _data)
       python tech_pages.py --dry      (prints what would be written)
"""
import html
import json
import sys
from pathlib import Path

SITE = "https://ai360trading.in"
DONE = Path("_data/tech_done.json")
CTA_FILE = Path("_data/tech_cta.txt")
DEFAULT_CTA = "PC ya data ki problem? Google par 'ai360services Haridwar' search karo."
NEXT_TAIL = " कल मिलते हैं एक नई टेक प्रॉब्लम के साथ।"


def slug(key):
    return key.replace("_", "-")


def page_url(key):
    return f"{SITE}/tech-tips/{slug(key)}/"


def cta():
    try:
        return CTA_FILE.read_text(encoding="utf-8").strip() or DEFAULT_CTA
    except Exception:
        return DEFAULT_CTA


def _clean_title(t):
    return t.replace(" #shorts", "").strip()


def _steps(topic):
    lines = list(topic.get("lines", []))
    if lines:
        lines[-1] = lines[-1].replace(NEXT_TAIL, "").strip()
    return [x.strip() for x in lines if x.strip()]


def render(key, topic, video, publish_at):
    """-> (file_text, hub_entry) or None when the topic cannot be rendered safely."""
    title = _clean_title(topic.get("yt_title") or topic.get("title") or key)
    steps = _steps(topic)
    if not steps or not video:
        return None
    body_text = " ".join(steps)
    if any(x in body_text + title for x in ("{{", "{%", "}}", "%}")):
        return None                                                  # Liquid-unsafe, skip rather than risk the site build
    desc = (steps[0] + " " + (steps[1] if len(steps) > 1 else ""))[:150].strip()
    url = page_url(key)
    fm = ["---", "layout: default",
          f"title: {json.dumps(title + ' | AI360 Technology', ensure_ascii=False)}",
          f"description: {json.dumps(desc, ensure_ascii=False)}",
          f"permalink: /tech-tips/{slug(key)}/",
          f"canonical: {url}",
          f"meta-og:title: {json.dumps(title, ensure_ascii=False)}",
          f"meta-og:description: {json.dumps(desc, ensure_ascii=False)}",
          f"meta-og:image: https://i.ytimg.com/vi/{video}/hqdefault.jpg",
          "---", ""]
    ld = {"@context": "https://schema.org", "@type": "VideoObject", "name": title, "description": desc,
          "thumbnailUrl": f"https://i.ytimg.com/vi/{video}/hqdefault.jpg", "uploadDate": publish_at,
          "embedUrl": f"https://www.youtube-nocookie.com/embed/{video}", "inLanguage": "hi-Latn"}
    li = "\n".join(f"    <li>{html.escape(s)}</li>" for s in steps)
    tags = [t for t in topic.get("tags", []) if t not in ("tech tips hinglish", "shorts")]
    rel = "\n".join(f"    <li>{html.escape(t)}</li>" for t in tags[:8])
    html_body = f"""<style>
  .tt-wrap{{max-width:760px;margin:0 auto;padding:0 4px}}
  .tt-hero h1{{font-size:26px;font-weight:900;line-height:1.3;color:#1e293b;margin:6px 0 10px}}
  .tt-vid{{position:relative;padding-top:56.25%;margin:14px 0;border-radius:12px;overflow:hidden;background:#000}}
  .tt-vid iframe{{position:absolute;inset:0;width:100%;height:100%;border:0}}
  .tt-card{{background:#fff;border:1px solid #e2e8f0;border-radius:14px;padding:16px 20px;margin:16px 0}}
  .tt-card li{{margin:8px 0;line-height:1.7;font-size:15.5px;color:#334155}}
  .tt-note{{background:#fffbeb;border:1px solid #fde68a;border-radius:12px;padding:12px 15px;font-size:13px;color:#78500a;line-height:1.6;margin:16px 0}}
  .tt-small{{font-size:13px;color:#64748b;line-height:1.6}}
</style>
<div class="tt-wrap">
  <div class="tt-hero"><h1>{html.escape(title)}</h1></div>
  <div class="tt-vid"><iframe src="https://www.youtube-nocookie.com/embed/{video}" title="{html.escape(title)}" loading="lazy" allowfullscreen></iframe></div>
  <div class="tt-card">
    <h2 style="font-size:18px;margin:0 0 6px">Aasan steps</h2>
    <ol>
{li}
    </ol>
  </div>
  <div class="tt-card">
    <h2 style="font-size:16px;margin:0 0 6px">Log ye bhi search karte hain</h2>
    <ul>
{rel}
    </ul>
  </div>
  <p class="tt-small">{html.escape(cta())}</p>
  <div class="tt-note">Ye jaankari general hai aur AI ki madad se tayyar ki gayi hai; video mein AI awaaz hai. Phone, charger, battery ya bijli ke andar ka kaam khud mat kijiye, kisi technician se karwaiye. Ye professional repair salah nahi hai.</div>
  <p class="tt-small"><a href="/tech-tips/">Aur tech problem ke solution dekhein</a> &middot; <a href="https://www.youtube.com/@AI360Techno" rel="noopener" target="_blank">YouTube par AI360 Technology</a></p>
</div>
<script type="application/ld+json">{json.dumps(ld, ensure_ascii=False)}</script>
"""
    return "\n".join(fm) + html_body, {"slug": slug(key), "title": title, "video": video, "date": publish_at[:10]}


def build_all(done_path=DONE, out_dir="_pages", data_path="_data/tech_pages.json", dry=False):
    try:
        done = json.loads(Path(done_path).read_text(encoding="utf-8"))
    except Exception as e:
        print(f"[TECH-PAGES] no done-list ({str(e)[:60]}), nothing to do")
        return 0
    import tech_short as TS
    entries, wrote = [], 0
    for d in done:
        key = d.get("topic")
        topic = TS.TOPICS.get(key)
        if not topic or "lines" not in topic:
            continue
        try:
            r = render(key, topic, d.get("video"), d.get("publish_at", ""))
        except Exception as e:
            print(f"[TECH-PAGES] {key} skipped: {str(e)[:60]}")
            continue
        if not r:
            continue
        text, entry = r
        entries.append(entry)
        p = Path(out_dir) / f"tt-{key.replace('_', '-')}.html"
        if dry:
            print(f"[TECH-PAGES] would write {p} ({len(text)} chars)")
            continue
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
            wrote += 1
    entries.sort(key=lambda e: e["date"], reverse=True)
    if not dry:
        new = json.dumps(entries, indent=1, ensure_ascii=False) + "\n"
        pd = Path(data_path)
        if not pd.exists() or pd.read_text(encoding="utf-8") != new:
            pd.write_text(new, encoding="utf-8")
    print(f"[TECH-PAGES] {len(entries)} pages, {wrote} written/updated")
    return 0


if __name__ == "__main__":
    sys.exit(build_all(dry="--dry" in sys.argv))
